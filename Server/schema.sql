-- LawPal database schema and access policies. Run in the Supabase SQL editor.
-- Safe to re-run. Columns were inferred from the application code and the live
-- user_forms table, so review before running on an existing project.

create table if not exists public.user_forms (
  id bigint generated by default as identity primary key,
  "firstName" text not null,
  "lastName" text not null,
  email text not null,
  subject text not null,
  message text not null
);

create table if not exists public.history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  prompt text[] not null,
  response text not null,
  service text not null,
  created_at timestamptz not null default now()
);

-- Contact submissions hold personal data: the public may submit but never read.
alter table public.user_forms enable row level security;
drop policy if exists "form" on public.user_forms;
drop policy if exists "contact form insert" on public.user_forms;
create policy "contact form insert" on public.user_forms
  for insert to anon, authenticated with check (true);

-- Chat history: each signed-in user sees and adds only their own rows.
alter table public.history enable row level security;
drop policy if exists "Allow insert for all users" on public.history;
drop policy if exists "Allow users to read their own chat history" on public.history;
drop policy if exists "own history read" on public.history;
drop policy if exists "own history insert" on public.history;
create policy "own history read" on public.history
  for select to authenticated using (auth.uid() = user_id);
create policy "own history insert" on public.history
  for insert to authenticated with check (auth.uid() = user_id);

